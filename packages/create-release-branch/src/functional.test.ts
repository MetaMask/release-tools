/**
 * Builds a link to a pull request of the repository of the functional tests.
 *
 * @param pullRequest - The number of the pull request.
 * @returns The Markdown link.
 */
function pullRequestLink(pullRequest: number): string {
  return `[#${pullRequest}](${LOCAL_CHANGELOG_REPOSITORY_URL}/pull/${pullRequest})`;
}

/**
 * Builds the lockfile of the Changesets monorepo.
 *
 * @param rangeOfB - The range of `@scope/b` that `@scope/c` depends on.
 * @returns The content of `yarn.lock`.
 */
function buildChangesetsMonorepoLockfile(rangeOfB: string): string {
  const workspaceEntry = (
    name: string,
    directoryPath: string,
    extraLines: string[] = [],
  ): string[] => [
    `  version: 0.0.0-use.local`,
    `  resolution: "${name}@workspace:${directoryPath}"`,
    ...extraLines,
    '  languageName: unknown',
    '  linkType: soft',
  ];
  return [
    '# This file is generated by running "yarn install" inside your project.',
    '# Manual changes might be lost - proceed with caution!',
    '',
    '__metadata:',
    '  version: 6',
    '',
    '"@scope/a@workspace:packages/a":',
    ...workspaceEntry('@scope/a', 'packages/a'),
    '',
    `"@scope/b@${rangeOfB}, @scope/b@workspace:packages/b":`,
    ...workspaceEntry('@scope/b', 'packages/b'),
    '',
    '"@scope/c@workspace:packages/c":',
    ...workspaceEntry('@scope/c', 'packages/c', [
      '  dependencies:',
      `    "@scope/b": ${rangeOfB}`,
    ]),
    '',
    '"@scope/d@workspace:packages/d":',
    ...workspaceEntry('@scope/d', 'packages/d'),
    '',
    '"@scope/l@workspace:packages/l":',
    ...workspaceEntry('@scope/l', 'packages/l'),
    '',
    '"@scope/monorepo@workspace:.":',
    ...workspaceEntry('@scope/monorepo', '.'),
    '',
  ].join('\n');
}

/**
 * Builds a monorepo that uses Changesets and commits all of its files, then
 * calls the given function with it. The monorepo has:
 *
 * - `a`, released by a minor Changeset, with legacy `Unreleased` entries;
 * - `b`, released by a major Changeset, without a changelog;
 * - `c`, which depends on `b`, with an empty `Unreleased` section;
 * - `d`, released with `a` by a straddling Changeset;
 * - `l`, which only has legacy `Unreleased` entries.
 *
 * @param callback - The function to call with the environment.
 * @returns Whatever the callback returns.
 */
async function withChangesetsMonorepo<CallbackReturnValue>(
  callback: (
    environment: MonorepoEnvironment<ChangesetsPackageNickname>,
  ) => Promise<CallbackReturnValue>,
): Promise<CallbackReturnValue> {
  return await withMonorepoProjectEnvironment(
    {
      packages: {
        $root$: {
          name: '@scope/monorepo',
          version: '1.0.0',
          directoryPath: '.',
        },
        a: { name: '@scope/a', version: '1.0.0', directoryPath: 'packages/a' },
        b: { name: '@scope/b', version: '1.0.0', directoryPath: 'packages/b' },
        c: { name: '@scope/c', version: '1.0.0', directoryPath: 'packages/c' },
        d: { name: '@scope/d', version: '0.1.0', directoryPath: 'packages/d' },
        l: { name: '@scope/l', version: '1.0.0', directoryPath: 'packages/l' },
      },
      workspaces: {
        '.': ['packages/*'],
      },
      changesets: [
        {
          id: 'brave-cats-sing',
          releases: { '@scope/a': 'minor' },
          summary: buildLocalChangelogSummary(
            'Added',
            'Add a feature to a',
            10,
          ),
        },
        {
          id: 'calm-dogs-run',
          releases: { '@scope/b': 'major' },
          summary: buildLocalChangelogSummary(
            'Removed',
            'Remove the old API of b',
            12,
          ),
        },
        {
          id: 'eager-owls-fly',
          releases: { '@scope/a': 'patch', '@scope/d': 'minor' },
          summary: buildLocalChangelogSummary(
            'Fixed',
            'Fix a and extend d',
            13,
          ),
        },
      ],
      createInitialCommit: false,
    },
    async (environment) => {
      await environment.writeFileWithinPackage(
        'a',
        'CHANGELOG.md',
        buildChangelog(`
          ## [Unreleased]

          ### Added

          - Add a legacy feature to a (${pullRequestLink(1)})

          ## [1.0.0]

          ### Added

          - Initial release (${pullRequestLink(0)})

          [Unreleased]: ${LOCAL_CHANGELOG_REPOSITORY_URL}/compare/@scope/a@1.0.0...HEAD
          [1.0.0]: ${LOCAL_CHANGELOG_REPOSITORY_URL}/releases/tag/@scope/a@1.0.0
        `),
      );
      await environment.updateJsonFileWithinPackage('c', 'package.json', {
        dependencies: { '@scope/b': '^1.0.0' },
      });
      await environment.writeFileWithinPackage(
        'c',
        'CHANGELOG.md',
        buildChangelog(`
          ## [Unreleased]

          ## [1.0.0]

          ### Added

          - Initial release (${pullRequestLink(0)})

          [Unreleased]: ${LOCAL_CHANGELOG_REPOSITORY_URL}/compare/@scope/c@1.0.0...HEAD
          [1.0.0]: ${LOCAL_CHANGELOG_REPOSITORY_URL}/releases/tag/@scope/c@1.0.0
        `),
      );
      await environment.writeFileWithinPackage(
        'l',
        'CHANGELOG.md',
        buildChangelog(`
          ## [Unreleased]

          ### Fixed

          - Fix a legacy bug in l (${pullRequestLink(2)})

          ## [1.0.0]

          ### Added

          - Initial release (${pullRequestLink(0)})

          [Unreleased]: ${LOCAL_CHANGELOG_REPOSITORY_URL}/compare/@scope/l@1.0.0...HEAD
          [1.0.0]: ${LOCAL_CHANGELOG_REPOSITORY_URL}/releases/tag/@scope/l@1.0.0
        `),
      );
      await environment.writeFile(
        'yarn.lock',
        buildChangesetsMonorepoLockfile('^1.0.0'),
      );
      await environment.createCommit('Set up the monorepo (#20)');
      return await callback(environment);
    },
  );
}

/**
 * Reads the subjects of the latest commits, newest first.
 *
 * @param environment - The environment.
 * @param count - The number of commits to read.
 * @returns The subjects.
 */
async function readLatestCommitSubjects(
  environment: MonorepoEnvironment<ChangesetsPackageNickname>,
  count: number,
): Promise<string[]> {
  const { stdout } = await environment.runCommand('git', [
    'log',
    '--pretty=%s',
    `--max-count=${count}`,
  ]);
  return stdout.split('\n');
}

/**
 * Lists the files that a commit changes.
 *
 * @param environment - The environment.
 * @param revision - The commit.
 * @returns The paths of the changed files, sorted.
 */
async function readChangedFiles(
  environment: MonorepoEnvironment<ChangesetsPackageNickname>,
  revision: string,
): Promise<string[]> {
  const { stdout } = await environment.runCommand('git', [
    'show',
    '--name-only',
    '--pretty=format:',
    revision,
  ]);
  return stdout.split('\n').filter((line) => line !== '');
}

/**
 * Lists the files in the `.changeset` directory.
 *
 * @param environment - The environment.
 * @returns The file names, sorted.
 */
async function listChangesetDirectory(
  environment: MonorepoEnvironment<ChangesetsPackageNickname>,
): Promise<string[]> {
  const { stdout } = await environment.runCommand('ls', ['.changeset']);
  return stdout.split('\n');
}

